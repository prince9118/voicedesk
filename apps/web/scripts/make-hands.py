"""Generates src/home/hands-data.ts: the two hands from Michelangelo's "Creation of Adam" as ASCII cells.

Source image (public domain): https://commons.wikimedia.org/wiki/File:Michelangelo_-_Creation_of_Adam_(cropped).jpg

Each arm is cut out of the fresco (separated from the plaster sky by colour), rotated so God's hand
reaches down from the upper right and Adam's rises from the bottom, then sampled into a grid.
Every cell keeps its brightness and a muted colour; the browser picks the glyph and animates it.

Usage (needs Pillow and NumPy):  python scripts/make-hands.py path/to/adam.jpg src/home/hands-data.ts
"""

import json
import sys

import numpy as np
from PIL import Image, ImageFilter

# Crop boxes in the 3524x1599 original: (left, top, right, bottom).
GOD = (1335, 520, 2250, 880)
ADAM = (560, 590, 1335, 900)
CELL = 16  # source pixels per cell after rotation


def mask_for(crop: Image.Image) -> np.ndarray:
    rgb = np.asarray(crop, dtype=np.float32) / 255
    lum = rgb @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
    mx, mn = rgb.max(axis=2), rgb.min(axis=2)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-6), 0)
    # The plaster sky is light and nearly grey; skin and cloth are darker or warmer.
    sky_lum = np.percentile(lum, 85)
    sky_sat = np.percentile(sat, 30)
    mask = (lum < sky_lum - 0.10) | (sat > sky_sat + 0.13)
    img = Image.fromarray((mask * 255).astype(np.uint8))
    # Close small gaps, then drop specks (cracks in the plaster).
    img = img.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(9)).filter(ImageFilter.MaxFilter(5))
    return np.asarray(img) > 127


def fingertip(mask: np.ndarray, side: str) -> tuple[int, int]:
    """The arm's extreme point on the given side: where the index finger ends."""
    ys, xs = np.nonzero(mask)
    x = xs.min() if side == "left" else xs.max()
    near = np.abs(xs - x) <= 4
    return int(x), int(ys[near].mean())


def largest_shape(cells):
    """Keep the biggest 8-connected group of cells: drops stray bits (curled fingers, plaster cracks)."""
    at = {(c[0], c[1]): c for c in cells}
    seen, best = set(), []
    for key in at:
        if key in seen:
            continue
        group, stack = [], [key]
        seen.add(key)
        while stack:
            x, y = stack.pop()
            group.append(at[(x, y)])
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    n = (x + dx, y + dy)
                    if n in at and n not in seen:
                        seen.add(n)
                        stack.append(n)
        if len(group) > len(best):
            best = group
    return sorted(best, key=lambda c: (c[1], c[0]))


def cells(box, angle, tip_side):
    crop = Image.open(sys.argv[1]).convert("RGB").crop(box)
    m0 = mask_for(crop)
    mask = Image.fromarray((m0 * 255).astype(np.uint8))
    # Track the fingertip through the rotation with a marker image (robust to PIL's expand maths).
    marker = Image.new("L", crop.size, 0)
    tx, ty = fingertip(m0, tip_side)
    marker.paste(255, (tx - 3, ty - 3, tx + 4, ty + 4))
    crop = crop.rotate(angle, resample=Image.BICUBIC, expand=True, fillcolor=(230, 222, 205))
    mask = mask.rotate(angle, resample=Image.BILINEAR, expand=True)
    marker = np.asarray(marker.rotate(angle, resample=Image.BILINEAR, expand=True))
    my, mx = np.unravel_index(marker.argmax(), marker.shape)
    rgb = np.asarray(crop, dtype=np.float32)
    m = np.asarray(mask, dtype=np.float32) / 255
    rows, cols = m.shape[0] // CELL, m.shape[1] // CELL
    out = []
    for r in range(rows):
        for c in range(cols):
            sl = (slice(r * CELL, (r + 1) * CELL), slice(c * CELL, (c + 1) * CELL))
            cover = float(m[sl].mean())
            if cover < 0.18 or (cover < 0.45 and float(rgb[sl].mean()) > 200):
                continue
            px = rgb[sl][m[sl] > 0.5]
            mean = px.mean(axis=0) if len(px) else rgb[sl].reshape(-1, 3).mean(axis=0)
            lum = float(mean @ np.array([0.299, 0.587, 0.114]))
            out.append([c, r, round(cover, 2), round(lum), *[int(v) for v in mean]])
    return {"cols": cols, "rows": rows, "tip": [int(mx) // CELL, int(my) // CELL], "cells": largest_shape(out)}


# Angles are counter-clockwise. God's arm (fingertip on the left) turns so it reaches down-left
# from the upper right; Adam's (fingertip on the right) turns so it rises from the bottom.
god = cells(GOD, 60, "left")
adam = cells(ADAM, 95, "right")

with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/make-hands.py from Michelangelo's \"Creation of Adam\" (public domain). Do not edit.\n")
    f.write("// Each cell: [col, row, coverage 0-1, luminance 0-255, r, g, b].\n")
    f.write("export type HandCell = [number, number, number, number, number, number, number];\n")
    f.write("export type HandSprite = { cols: number; rows: number; tip: [number, number]; cells: HandCell[] };\n")
    for name, data in (("GOD", god), ("ADAM", adam)):
        f.write(f"export const {name}: HandSprite = {json.dumps(data, separators=(',', ':'))};\n")
print("god tip", god["tip"], "adam tip", adam["tip"])
print("god", god["cols"], "x", god["rows"], len(god["cells"]), "cells; adam", adam["cols"], "x", adam["rows"], len(adam["cells"]), "cells")
